// Bundle backend (TypeScript + the pure engine package) into src/index.js for Forge.
import { build } from 'esbuild';
await build({
  entryPoints: ['backend/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  outfile: 'src/index.js',
  external: ['@forge/*'],
  logLevel: 'warning',
  banner: { js: '// GENERATED by build.mjs from backend/*.ts and packages/engine — do not edit' },
});
